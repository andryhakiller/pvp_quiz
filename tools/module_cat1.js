// ─── 1.2: PHYSICAL GEOGRAPHY CLEANUP ──────────────────────────────────────────
function cleanCat1_2() {
    const questions = cleanJson(path.join(SERVER_DIR, '1.2.txt'));
    let changed = 0;

    for (const q of questions) {
        // Remove parenthetical giveaways in options
        q.options = q.options.map(opt => {
            if (opt.includes('(') && opt.includes(')')) {
                // If only this option had parens, strip them
                const stripped = opt.replace(/\s*\([^)]*\)/g, '').trim();
                return stripped;
            }
            return opt;
        });

        // Question 37 fix (was guessing magnitude 8.8, 9.1, 9.5, 9.9)
        if (q.id === 'geography_physical_geography_37' || q.question.includes('Вальдивии')) {
            q.question = 'Какой океанический пролив между Южной Америкой и Антарктидой считается самым широким (около 820 км) и бурным на Земле?';
            q.options = ['Пролив Дрейка', 'Магелланов пролив', 'Берингов пролив', 'Мозамбикский пролив'];
            q.correctIndex = 0;
            changed++;
        }

        // Question 70 fix (Santorini / Thira)
        if (q.question && q.question.includes('минойское извержение')) {
            q.options = q.options.map(o => o.replace(/\s*\(Тира\)/g, '').trim());
            changed++;
        }
    }

    writeJson(path.join(SERVER_DIR, '1.2.txt'), questions);
    console.log(`✅ 1.2.txt cleaned: ${questions.length} questions`);
}

