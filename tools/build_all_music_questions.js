const fs = require('fs');
const path = require('path');

const SERVER_DIR = path.resolve(__dirname, '../server');

function saveSubcategory(filename, questions) {
  // Parity check
  questions.forEach((q, i) => {
    if (!Array.isArray(q.options) || q.options.length !== 4) {
      throw new Error(`File ${filename} Q#${i+1} does not have exactly 4 options!`);
    }
    const lens = q.options.map(o => o.length);
    const minL = Math.min(...lens);
    const maxL = Math.max(...lens);
    if (maxL > minL * 2.2 && (maxL - minL) > 20) {
      console.warn(`Parity warning ${filename} Q#${i+1}: ${JSON.stringify(q.options)}`);
    }
  });
  fs.writeFileSync(path.join(SERVER_DIR, filename), JSON.stringify(questions, null, 2), 'utf8');
  console.log(`✅ ${filename} written: ${questions.length} questions`);
}

