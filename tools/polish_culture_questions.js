const files = fs.readdirSync(SERVER_DIR).filter(f => /^\d+\.\d+\.txt$/.test(f));
let count = 0;

files.forEach(f => {
  const p = path.join(SERVER_DIR, f);
  const arr = JSON.parse(fs.readFileSync(p, 'utf8'));
  let mod = false;

  arr.forEach(q => {
    if (polish[q.id]) {
      q.question = polish[q.id].q;
      if (polish[q.id].opts) {
        q.options = polish[q.id].opts;
        q.correctIndex = 0; // will be shuffled by merge_and_validate
      }
      mod = true;
      count++;
    }
  });

  if (mod) fs.writeFileSync(p, JSON.stringify(arr, null, 2), 'utf8');
});

console.log(`✅ Polished ${count} literature and cinema questions.`);
