const targetFiles = [
  '11.1.txt', '11.2.txt', '11.3.txt', '11.4.txt',
  '12.1.txt', '12.2.txt', '12.3.txt', '12.4.txt', '12.5.txt', '12.6.txt', '12.7.txt'
];

let totalQuestionsProcessed = 0;
let totalParensCleaned = 0;
let totalQuestionsOverridden = 0;

targetFiles.forEach(fileName => {
  const filePath = path.join(SERVER_DIR, fileName);
  const backupPath = path.join(SCRATCH_BACKUP, fileName);

  // Backup original
  fs.copyFileSync(filePath, backupPath);

  const questions = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  const overrides = fileOverrides[fileName] || {};

  questions.forEach((q, idx) => {
    totalQuestionsProcessed++;
    const qNum = idx + 1;

    // 1. Check question text leak fixes
    if (questionLeakFixes[q.question]) {
      q.question = questionLeakFixes[q.question];
    }

    // 2. Check explicit override first
    if (overrides[qNum]) {
      const ov = overrides[qNum];
      q.options = [...ov.opts];
      q.correctIndex = ov.opts.indexOf(ov.cOpt);
      if (q.correctIndex === -1) {
        throw new Error(`Override for ${fileName} Q#${qNum}: cOpt "${ov.cOpt}" not in opts!`);
      }
      totalQuestionsOverridden++;
      return;
    }

    // 3. Otherwise clean parens from options
    q.options = q.options.map(opt => {
      const cleaned = cleanOptionParens(opt);
      if (cleaned !== opt) totalParensCleaned++;
      return cleaned;
    });
  });

  // Write updated file
  fs.writeFileSync(filePath, JSON.stringify(questions, null, 2), 'utf8');
  console.log(`✅ ${fileName} updated successfully.`);
});

console.log(`\n🎉 Processed ${targetFiles.length} files (${totalQuestionsProcessed} questions).`);
console.log(`Paren occurrences cleaned: ${totalParensCleaned}`);
console.log(`Targeted questions rebalanced: ${totalQuestionsOverridden}`);
